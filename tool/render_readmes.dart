#!/usr/bin/env dart
// Render README.md files from *.template.md by injecting marked doc regions.
//
// Usage (from repo root):
//   dart run tool/render_readmes.dart
//
// Include markers in docs:
//   <!-- fluau:include-begin id="try-example" -->
//   ...
//   <!-- fluau:include-end id="try-example" -->
//
// In templates:
//   {{include:docs/GETTING_STARTED.md#try-example}}

import 'dart:io';

final _includeRe = RegExp(r'\{\{include:([^}]+)\}\}');
final _beginRe = RegExp(
  r'<!--\s*fluau:include-begin\s+id="([^"]+)"\s*-->',
);
final _endRe = RegExp(
  r'<!--\s*fluau:include-end\s+id="([^"]+)"\s*-->',
);
final _mdLinkRe = RegExp(r'\[([^\]]+)\]\(([^)]+)\)');

const _banner =
    '<!-- Generated by tool/render_readmes.dart — edit *.template.md / docs, not this file. -->\n';

void main(List<String> args) {
  final root = _findRepoRoot();
  final jobs = <_Job>[
    _Job(
      template: File('$root/README.template.md'),
      output: File('$root/README.md'),
      outputDir: root,
    ),
    _Job(
      template: File('$root/packages/fluau/README.template.md'),
      output: File('$root/packages/fluau/README.md'),
      outputDir: '$root/packages/fluau',
    ),
  ];

  for (final job in jobs) {
    if (!job.template.existsSync()) {
      stderr.writeln('Missing template: ${job.template.path}');
      exit(1);
    }
    final rendered = _render(root, job);
    job.output.writeAsStringSync(rendered);
    stdout.writeln('Wrote ${job.output.path}');
  }
}

String _findRepoRoot() {
  var dir = Directory.current;
  while (true) {
    if (File('${dir.path}/tool/render_readmes.dart').existsSync() &&
        Directory('${dir.path}/docs').existsSync()) {
      return dir.path;
    }
    final parent = dir.parent;
    if (parent.path == dir.path) {
      stderr.writeln('Could not find repo root (run from fluau checkout).');
      exit(1);
    }
    dir = parent;
  }
}

String _render(String root, _Job job) {
  var text = job.template.readAsStringSync();
  text = text.replaceAllMapped(_includeRe, (m) {
    final spec = m.group(1)!.trim();
    final hash = spec.indexOf('#');
    if (hash < 0) {
      throw StateError('Include missing #id: {{include:$spec}}');
    }
    final relPath = spec.substring(0, hash);
    final id = spec.substring(hash + 1);
    final source = File('$root/$relPath');
    if (!source.existsSync()) {
      throw StateError('Include source missing: $relPath');
    }
    final blob = _extractInclude(source.readAsStringSync(), id, relPath);
    final sourceDir = File('$root/$relPath').parent.path;
    return _rewriteLinks(blob, sourceDir: sourceDir, outputDir: job.outputDir);
  });

  if (!text.startsWith(_banner)) {
    text = '$_banner\n$text';
  }
  if (!text.endsWith('\n')) {
    text = '$text\n';
  }
  return text;
}

String _extractInclude(String doc, String id, String path) {
  final begin = _beginRe.allMatches(doc).where((m) => m.group(1) == id);
  if (begin.isEmpty) {
    throw StateError('Include begin not found: $path#$id');
  }
  final startMatch = begin.first;
  final afterBegin = startMatch.end;
  final endMatches = _endRe.allMatches(doc).where((m) => m.group(1) == id);
  Match? endMatch;
  for (final m in endMatches) {
    if (m.start >= afterBegin) {
      endMatch = m;
      break;
    }
  }
  if (endMatch == null) {
    throw StateError('Include end not found: $path#$id');
  }
  final blob = doc.substring(afterBegin, endMatch.start).trim();
  if (blob.isEmpty) {
    throw StateError('Include empty: $path#$id');
  }
  return blob;
}

/// Rewrite relative markdown links so they resolve from [outputDir].
String _rewriteLinks(
  String markdown, {
  required String sourceDir,
  required String outputDir,
}) {
  return markdown.replaceAllMapped(_mdLinkRe, (m) {
    final label = m.group(1)!;
    final target = m.group(2)!;
    if (_isExternalOrAbsolute(target)) {
      return m.group(0)!;
    }
    final hash = target.indexOf('#');
    final pathPart = hash < 0 ? target : target.substring(0, hash);
    final fragment = hash < 0 ? '' : target.substring(hash);
    if (pathPart.isEmpty) {
      return m.group(0)!;
    }
    final abs = _absoluteFrom(sourceDir, pathPart);
    final rel = _relativePath(outputDir, abs);
    return '[$label]($rel$fragment)';
  });
}

bool _isExternalOrAbsolute(String target) {
  return target.startsWith('http://') ||
      target.startsWith('https://') ||
      target.startsWith('mailto:') ||
      target.startsWith('/') ||
      target.startsWith('#');
}

String _absoluteFrom(String baseDir, String rel) {
  final parts = <String>[];
  for (final p in [...baseDir.split(Platform.pathSeparator), ...rel.split('/')]) {
    if (p.isEmpty || p == '.') continue;
    if (p == '..') {
      if (parts.isNotEmpty) parts.removeLast();
      continue;
    }
    parts.add(p);
  }
  // Preserve leading slash on Unix absolute base.
  if (baseDir.startsWith('/')) {
    return '/${parts.join('/')}';
  }
  return parts.join('/');
}

String _relativePath(String fromDir, String toAbs) {
  final from = fromDir.split(Platform.pathSeparator).where((e) => e.isNotEmpty).toList();
  final to = toAbs.split('/').where((e) => e.isNotEmpty).toList();
  // Both absolute Unix paths
  var i = 0;
  while (i < from.length && i < to.length && from[i] == to[i]) {
    i++;
  }
  final up = List.filled(from.length - i, '..');
  final down = to.sublist(i);
  final rel = [...up, ...down].join('/');
  return rel.isEmpty ? '.' : rel;
}

class _Job {
  _Job({
    required this.template,
    required this.output,
    required this.outputDir,
  });

  final File template;
  final File output;
  final String outputDir;
}

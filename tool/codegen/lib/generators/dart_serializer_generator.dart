/// Dart serializer generator for Lua plugin framework
///
/// Generates:
/// - fromJson() extensions for each Lua class
/// - LuaWidgetRegistry with type-to-constructor mapping
/// - Helper methods for deserialization
/// - Enum parsers for enum properties

import '../models/widget_info.dart';

/// Main Dart serializer generator
class DartSerializerGenerator {
  /// Set of enum types that have already had parsers generated
  final Set<String> _generatedEnumParsers = {};
  
  /// Buffer for collecting enum parser functions
  final StringBuffer _enumParsersBuffer = StringBuffer();

  /// Generate all serialization code for the given classes
  String generateAll(List<LuaClassInfo> classes) {
    final buffer = StringBuffer();
    
    _writeHeader(buffer);
    buffer.writeln();
    
    // Generate serializers for each class
    for (final luaClass in classes) {
      _writeSerializer(buffer, luaClass, classes);
      buffer.writeln();
    }
    
    // Generate enum parsers (collected during serializer generation)
    buffer.writeln(_enumParsersBuffer.toString());
    
    // Generate registry
    _writeRegistry(buffer, classes);
    
    return buffer.toString();
  }

  /// Reset the generator state (for testing)
  void clear() {
    _generatedEnumParsers.clear();
    _enumParsersBuffer.clear();
  }
  
  void _writeHeader(StringBuffer buffer) {
    buffer.writeln('// Generated by lua_plugin_codegen');
    buffer.writeln('// DO NOT EDIT - This file is automatically generated');
    buffer.writeln();
    buffer.writeln('part of \'widget.dart\';');
  }
  
  void _writeSerializer(StringBuffer buffer, LuaClassInfo luaClass, List<LuaClassInfo> allClasses) {
    final className = luaClass.dartClassName;
    
    buffer.writeln('/// Serializer for ${className}');
    buffer.writeln('/// Converts JSON maps to ${className} instances');
    buffer.writeln('extension _${className}Serializer on ${className} {');
    buffer.writeln('  /// Deserialize from JSON map');
    buffer.writeln('  static ${className} fromJson(Map<String, dynamic> json) {');
    buffer.writeln('    return ${className}(');
    
    // Generate each property
    for (final prop in luaClass.properties) {
      final value = _generatePropertyValue(prop, luaClass, allClasses);
      buffer.writeln('      ${prop.name}: $value,');
    }
    
    buffer.writeln('    );');
    buffer.writeln('  }');
    buffer.writeln('}');
  }
  
  /// Generate the Dart expression to extract a property value from JSON
  String _generatePropertyValue(PropertyInfo prop, LuaClassInfo luaClass, List<LuaClassInfo> allClasses) {
    final jsonKey = prop.name;
    
    if (prop.isCallback) {
      // Callback ID is a string
      return 'json[\'${jsonKey}\'] as String?';
    }
    
    if (prop.isChildList) {
      // List of widgets - use the type information to deserialize
      return '_deserializeWidgetList(json[\'${jsonKey}\'] as List?)';
    }
    
    if (prop.isChildWidget) {
      // Single widget child
      return 'json[\'${jsonKey}\'] != null ? _deserializeWidget(json[\'${jsonKey}\'] as Map<String, dynamic>) : null';
    }
    
    if (prop.isDataClass) {
      // Nested data class
      final nestedClassName = prop.nestedClassName ?? prop.nonNullableDartType;
      return 'json[\'${jsonKey}\'] != null ? _${nestedClassName}Serializer.fromJson(json[\'${jsonKey}\'] as Map<String, dynamic>) : null';
    }
    
    if (prop.isEnum) {
      // Enum property - generate parser if not already generated
      final enumType = prop.nonNullableDartType;
      _generateEnumParser(enumType, prop.enumValues ?? []);
      return 'json[\'${jsonKey}\'] != null ? _parse$enumType(json[\'${jsonKey}\'] as String?) : null';
    }
    
    // Primitive types
    return _generatePrimitiveValue(prop);
  }

  /// Generate an enum parser function
  void _generateEnumParser(String enumType, List<String> values) {
    if (_generatedEnumParsers.contains(enumType)) return;
    _generatedEnumParsers.add(enumType);
    
    _enumParsersBuffer.writeln('$enumType? _parse$enumType(String? value) {');
    _enumParsersBuffer.writeln('  if (value == null) return null;');
    _enumParsersBuffer.writeln('  switch (value) {');
    for (final val in values) {
      _enumParsersBuffer.writeln('    case \'$val\': return $enumType.$val;');
    }
    _enumParsersBuffer.writeln('    default: throw FormatException(\'Unknown $enumType value: \$value\');');
    _enumParsersBuffer.writeln('  }');
    _enumParsersBuffer.writeln('}');
    _enumParsersBuffer.writeln();
  }
  
  String _generatePrimitiveValue(PropertyInfo prop) {
    final jsonKey = prop.name;
    final type = TypeMapping.getForDartType(prop.dartType);
    final cleanType = prop.nonNullableDartType;
    
    if (type != null) {
      // Use the predefined mapping
      if (prop.isNullable) {
        // For nullable types, we need to check if the value exists and cast it
        final expression = type.dartFromJson.replaceAll('value', 'json[\'$jsonKey\']');
        return 'json[\'$jsonKey\'] != null ? $expression : null';
      } else {
        return type.dartFromJson.replaceAll('value', 'json[\'$jsonKey\']');
      }
    }
    
    // Fallback for unknown types
    if (prop.isNullable) {
      return 'json[\'$jsonKey\'] as $cleanType?';
    } else {
      return 'json[\'$jsonKey\'] as $cleanType';
    }
  }
  
  void _writeRegistry(StringBuffer buffer, List<LuaClassInfo> classes) {
    buffer.writeln('/// Widget registry for Lua widgets');
    buffer.writeln('/// Maps widget type names to their deserialization functions');
    buffer.writeln('class LuaWidgetRegistry {');
    buffer.writeln('  static final Map<String, LuaWidgetInterface Function(Map<String, dynamic>)> _builders = {');
    
    // Add widget builders - these are used by fromJson
    for (final luaClass in classes.where((c) => c.isWidget)) {
      buffer.writeln('    \'${luaClass.luaName}\': (json) => _${luaClass.dartClassName}Serializer.fromJson(json),');
    }
    
    buffer.writeln('  };');
    buffer.writeln();
    buffer.writeln('  /// Deserialize a widget from JSON (without building it)');
    buffer.writeln('  /// The [type] parameter should be the Lua widget type name (e.g., \'Text\', \'Button\').');
    buffer.writeln('  static LuaWidgetInterface fromJson(String type, Map<String, dynamic> json) {');
    buffer.writeln('    final builder = _builders[type];');
    buffer.writeln('    if (builder != null) {');
    buffer.writeln('      return builder(json);');
    buffer.writeln('    }');
    buffer.writeln('    return const LuaEmptyWidget();');
    buffer.writeln('  }');
    buffer.writeln();
    buffer.writeln('  /// Build a widget from a JSON map (with type field) and context');
    buffer.writeln('  /// This is the main entry point for building widgets from Lua JSON.');
    buffer.writeln('  static Widget buildFromMap(BuildContext context, Map<String, dynamic> widgetMap) {');
    buffer.writeln('    final widgetType = widgetMap[\'type\'] as String?;');
    buffer.writeln('    if (widgetType == null) {');
    buffer.writeln('      return const LuaEmptyWidget();');
    buffer.writeln('    }');
    buffer.writeln();
    buffer.writeln('    // Remove type from properties');
    buffer.writeln('    final properties = Map<String, dynamic>.from(widgetMap);');
    buffer.writeln('    properties.remove(\'type\');');
    buffer.writeln();
    buffer.writeln('    // Deserialize and build');
    buffer.writeln('    final widget = fromJson(widgetType, properties);');
    buffer.writeln('    return widget.build(context);');
    buffer.writeln('  }');
    buffer.writeln('}');
    buffer.writeln();
    
    // Write helper functions
    _writeHelperFunctions(buffer, classes);
  }
  
  void _writeHelperFunctions(StringBuffer buffer, List<LuaClassInfo> classes) {
    // Deserialize a list of child widgets from JSON
    buffer.writeln('/// Deserialize a list of child widgets from JSON');
    buffer.writeln('/// Each child widget JSON should have a "type" field indicating its widget type.');
    buffer.writeln('List<LuaWidgetInterface> _deserializeWidgetList(List<dynamic>? json) {');
    buffer.writeln('  if (json == null) return [];');
    buffer.writeln('  return json.map((item) => _deserializeWidget(item as Map<String, dynamic>)).toList();');
    buffer.writeln('}');
    buffer.writeln();
    
    // Deserialize a single widget from JSON
    buffer.writeln('/// Deserialize a single widget from JSON');
    buffer.writeln('/// This creates the widget instance but does NOT build it.');
    buffer.writeln('/// The build() method will be called later with proper BuildContext.');
    buffer.writeln('/// The JSON should have a "type" field indicating the widget type.');
    buffer.writeln('LuaWidgetInterface _deserializeWidget(Map<String, dynamic> json) {');
    buffer.writeln('  final widgetType = json[\'type\'] as String?;');
    buffer.writeln('  if (widgetType == null) {');
    buffer.writeln('    return const LuaEmptyWidget();');
    buffer.writeln('  }');
    buffer.writeln();
    buffer.writeln('  // Remove type from the JSON before deserializing');
    buffer.writeln('  final properties = Map<String, dynamic>.from(json);');
    buffer.writeln('  properties.remove(\'type\');');
    buffer.writeln();
    buffer.writeln('  // Use the registry to deserialize');
    buffer.writeln('  return LuaWidgetRegistry.fromJson(widgetType, properties);');
    buffer.writeln('}');
    buffer.writeln();
  }
}

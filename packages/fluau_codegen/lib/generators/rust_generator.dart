/// Rust code generator for Lua plugin framework
///
/// Emits a self-contained `lua_engine.rs`:
/// - Widget constructors (Lua → JSON string)
/// - Inline ui.getState / setState / registerCallback helpers
/// - `register_ui_catalog()` for `#[frb(init)]` / process start

import '../models/widget_info.dart';

/// Main Rust generator
class RustGenerator {
  String generateModule(List<LuaClassInfo> classes) {
    final buffer = StringBuffer();

    _writeHeader(buffer);
    _writeImports(buffer);
    buffer.writeln();

    _writeRegisterUiCatalog(buffer);
    buffer.writeln();

    _writeLuaApiSetup(buffer, classes);
    buffer.writeln();

    _writeExecuteFunction(buffer);
    buffer.writeln();

    _writeInlineHelpers(buffer);

    return buffer.toString();
  }

  void _writeHeader(StringBuffer buffer) {
    buffer.writeln('// Generated by fluau_codegen');
    buffer.writeln('// DO NOT EDIT - This file is automatically generated');
    buffer.writeln('//');
    buffer.writeln(
      '// Call `register_ui_catalog()` once at process start (e.g. #[frb(init)]).',
    );
    buffer.writeln(
      '// Or pass `ui_setup: Some(crate::lua_engine::setup_lua_api)` to fluau::setup.',
    );
    buffer.writeln();
  }

  void _writeImports(StringBuffer buffer) {
    buffer.writeln('use mlua::{Function, Lua, Result, Table, Value};');
    buffer.writeln(
      'use serde_json::{json, Value as JsonValue, Map as JsonMap};',
    );
    buffer.writeln();
  }

  void _writeRegisterUiCatalog(StringBuffer buffer) {
    buffer.writeln('/// Register this catalog with fluau (idempotent).');
    buffer.writeln('///');
    buffer.writeln(
      '/// Call from `#[frb(init)]` / process start. Does not clear HostAPIs.',
    );
    buffer.writeln(
      'pub fn register_ui_catalog() -> std::result::Result<(), String> {',
    );
    buffer.writeln(
      '    fluau::set_ui_setup(setup_lua_api)',
    );
    buffer.writeln('}');
  }

  void _writeLuaApiSetup(StringBuffer buffer, List<LuaClassInfo> classes) {
    buffer.writeln(
      '/// Install `ui.*` widget constructors into a Lua VM (session hook).',
    );
    buffer.writeln('pub fn setup_lua_api(lua: &Lua) -> Result<()> {');
    buffer.writeln('    let ui = lua.create_table()?;');
    buffer.writeln();

    for (final luaClass in classes.where((c) => c.isWidget)) {
      for (final ctor in luaClass.constructors) {
        _writeWidgetConstructor(buffer, luaClass, ctor);
      }
    }

    buffer.writeln();
    buffer.writeln('    // State management functions');
    buffer.writeln('    ui.set("getState", lua.create_function(|_, key: String| {');
    buffer.writeln(
      '        catalog_state::get_state(&key).map_err(mlua::Error::runtime)',
    );
    buffer.writeln('    })?)?;');
    buffer.writeln();
    buffer.writeln(
      '    ui.set("setState", lua.create_function(|_, (key, value): (String, String)| {',
    );
    buffer.writeln(
      '        catalog_state::set_state(key, value).map_err(mlua::Error::runtime)',
    );
    buffer.writeln('    })?)?;');
    buffer.writeln();
    buffer.writeln('    ui.set("getAllState", lua.create_function(|_, ()| {');
    buffer.writeln(
      '        catalog_state::get_all_state().map_err(mlua::Error::runtime)',
    );
    buffer.writeln('    })?)?;');

    buffer.writeln();
    buffer.writeln('    // Callback registration');
    buffer.writeln(
      '    ui.set("registerCallback", lua.create_function(|lua, func: Function| {',
    );
    buffer.writeln(
      '        catalog_callbacks::register_callback(lua, func)',
    );
    buffer.writeln('            .map_err(|e| mlua::Error::runtime(e.to_string()))');
    buffer.writeln('    })?)?;');

    buffer.writeln();
    buffer.writeln('    lua.globals().set("ui", ui)?;');
    buffer.writeln('    Ok(())');
    buffer.writeln('}');

    final needsNesting = classes
        .where((c) => c.isWidget)
        .expand((c) => c.constructors)
        .any((ctor) => ctor.luaName.contains('.'));
    if (needsNesting) {
      buffer.writeln();
      buffer.writeln(
        'fn ensure_ui_table(lua: &Lua, parent: &Table, key: &str) -> Result<Table> {',
      );
      buffer.writeln('    match parent.get::<Table>(key) {');
      buffer.writeln('        Ok(t) => Ok(t),');
      buffer.writeln('        Err(_) => {');
      buffer.writeln('            let t = lua.create_table()?;');
      buffer.writeln('            parent.set(key, t.clone())?;');
      buffer.writeln('            Ok(t)');
      buffer.writeln('        }');
      buffer.writeln('    }');
      buffer.writeln('}');
    }
  }

  void _writeWidgetConstructor(
    StringBuffer buffer,
    LuaClassInfo luaClass,
    LuaConstructorInfo ctor,
  ) {
    final luaName = ctor.luaName;
    final parts = luaName.split('.');
    final leaf = parts.last;

    buffer.writeln('    // $luaName widget constructor');
    if (parts.length == 1) {
      buffer.writeln(
        '    ui.set("$leaf", lua.create_function(|lua, args: Table| -> Result<Value> {',
      );
    } else {
      buffer.writeln('    {');
      buffer.writeln('        let mut __parent = ui.clone();');
      for (var i = 0; i < parts.length - 1; i++) {
        final seg = parts[i];
        buffer.writeln(
          '        __parent = ensure_ui_table(lua, &__parent, "$seg")?;',
        );
      }
      buffer.writeln(
        '        __parent.set("$leaf", lua.create_function(|lua, args: Table| -> Result<Value> {',
      );
    }

    buffer.writeln('        let mut map = JsonMap::new();');
    // JSON / Dart registry type id stays the full dotted string.
    buffer.writeln('        map.insert("type".to_string(), json!("$luaName"));');
    buffer.writeln();

    for (final prop in ctor.parameters) {
      _writePropertyExtraction(buffer, luaName, prop);
    }

    buffer.writeln(
      '        let json_str = serde_json::to_string(&map).map_err(|e| mlua::Error::runtime(e.to_string()))?;',
    );
    buffer.writeln(
      '        Ok(Value::String(lua.create_string(&json_str)?))',
    );
    if (parts.length == 1) {
      buffer.writeln('    })?)?;');
    } else {
      buffer.writeln('        })?)?;');
      buffer.writeln('    }');
    }
    buffer.writeln();
  }

  void _writePropertyExtraction(
    StringBuffer buffer,
    String luaName,
    PropertyInfo prop,
  ) {
    final propName = prop.name;
    final isRequired = prop.required;

    if (prop.isCallback) {
      buffer.writeln('        // Handle $propName (event payload)');
      buffer.writeln(
        '        if let Ok(event_value) = args.get::<Option<Value>>("$propName") {',
      );
      buffer.writeln('            if let Some(v) = event_value {');
      buffer.writeln(
        '                let event_json = fluau::json_util::lua_to_json(v)',
      );
      buffer.writeln(
        '                    .map_err(|e| mlua::Error::runtime(e.to_string()))?;',
      );
      buffer.writeln(
        '                map.insert("$propName".to_string(), event_json);',
      );
      buffer.writeln('            }');
      buffer.writeln('        }');
    } else if (prop.isChildList) {
      buffer.writeln('        // Handle $propName (child list)');
      buffer.writeln(
        '        if let Ok(children_table) = args.get::<Option<Table>>("$propName") {',
      );
      buffer.writeln('            if let Some(table) = children_table {');
      buffer.writeln('                let mut children_json = Vec::new();');
      buffer.writeln('                for pair in table.pairs::<Value, Value>() {');
      buffer.writeln('                    if let Ok((_, child_value)) = pair {');
      buffer.writeln(
        '                        if let Value::String(child_str) = child_value {',
      );
      buffer.writeln(
        '                            if let Ok(parsed) = serde_json::from_str::<JsonValue>(&child_str.to_string_lossy()) {',
      );
      buffer.writeln(
        '                                children_json.push(parsed);',
      );
      buffer.writeln('                            }');
      buffer.writeln('                        }');
      buffer.writeln('                    }');
      buffer.writeln('                }');
      buffer.writeln(
        '                map.insert("$propName".to_string(), json!(children_json));',
      );
      buffer.writeln('            }');
      buffer.writeln('        }');
    } else if (prop.isStringList) {
      buffer.writeln('        // Handle $propName (string list)');
      buffer.writeln(
        '        if let Ok(list_value) = args.get::<Option<Value>>("$propName") {',
      );
      buffer.writeln('            if let Some(v) = list_value {');
      buffer.writeln(
        '                let list_json = fluau::json_util::lua_to_json(v)',
      );
      buffer.writeln(
        '                    .map_err(|e| mlua::Error::runtime(e.to_string()))?;',
      );
      buffer.writeln(
        '                map.insert("$propName".to_string(), list_json);',
      );
      buffer.writeln('            }');
      buffer.writeln('        }');
    } else if (prop.isChildWidget) {
      buffer.writeln('        // Handle $propName (child widget)');
      buffer.writeln(
        '        if let Ok(child_value) = args.get::<Option<Value>>("$propName") {',
      );
      buffer.writeln(
        '            if let Some(Value::String(child_str)) = child_value {',
      );
      buffer.writeln(
        '                if let Ok(parsed) = serde_json::from_str::<JsonValue>(&child_str.to_string_lossy()) {',
      );
      buffer.writeln(
        '                    map.insert("$propName".to_string(), parsed);',
      );
      buffer.writeln('                }');
      buffer.writeln('            }');
      buffer.writeln('        }');
    } else if (prop.isDataClass) {
      buffer.writeln('        // Handle $propName (data class)');
      buffer.writeln('        let $propName: Option<String> = args.get("$propName")');
      buffer.writeln('            .ok()');
      buffer.writeln('            .and_then(|v| v.to_string().ok());');
      buffer.writeln('        if let Some(v) = $propName {');
      buffer.writeln('            map.insert("$propName".to_string(), json!(v));');
      buffer.writeln('        }');
    } else if (prop.isEnum) {
      buffer.writeln('        // Handle $propName (enum)');
      if (isRequired) {
        buffer.writeln('        let $propName: String = args.get("$propName")?;');
        _writeEnumValidation(
          buffer,
          luaName,
          propName,
          propName,
          prop.enumValues,
        );
        buffer.writeln(
          '        map.insert("$propName".to_string(), json!($propName));',
        );
      } else {
        buffer.writeln(
          '        let $propName: Option<String> = args.get("$propName").ok();',
        );
        buffer.writeln('        if let Some(ref v) = $propName {');
        _writeEnumValidation(
          buffer,
          luaName,
          propName,
          'v',
          prop.enumValues,
          indent: '            ',
        );
        buffer.writeln(
          '            map.insert("$propName".to_string(), json!(v));',
        );
        buffer.writeln('        }');
      }
    } else {
      final rustType = _getRustPrimitiveType(prop);

      buffer.writeln('        // Handle $propName ($rustType)');
      if (isRequired) {
        buffer.writeln(
          '        let $propName: $rustType = args.get("$propName")?;',
        );
        buffer.writeln(
          '        map.insert("$propName".to_string(), json!($propName));',
        );
      } else {
        buffer.writeln(
          '        let $propName: Option<$rustType> = args.get("$propName").ok();',
        );
        buffer.writeln('        if let Some(v) = $propName {');
        buffer.writeln(
          '            map.insert("$propName".to_string(), json!(v));',
        );
        buffer.writeln('        }');
      }
    }
    buffer.writeln();
  }

  void _writeEnumValidation(
    StringBuffer buffer,
    String luaName,
    String displayName,
    String rustExpr,
    List<String>? enumValues, {
    String indent = '        ',
  }) {
    if (enumValues == null || enumValues.isEmpty) return;

    final validValues = enumValues.map((v) => '"$v"').join(', ');
    buffer.writeln(
      '$indent if ![$validValues].contains(&$rustExpr.as_str()) {',
    );
    buffer.writeln(
      '$indent     return Err(mlua::Error::runtime("$luaName: invalid $displayName value"));',
    );
    buffer.writeln('$indent }');
  }

  void _writeExecuteFunction(StringBuffer buffer) {
    buffer.writeln('/// Execute a one-shot Lua script that returns a widget JSON string.');
    buffer.writeln(
      'pub fn execute_ui_script(script: &str) -> std::result::Result<String, String> {',
    );
    buffer.writeln('    let lua = Lua::new();');
    buffer.writeln('    setup_lua_api(&lua).map_err(|e| e.to_string())?;');
    buffer.writeln();
    buffer.writeln('    let result: Value = lua');
    buffer.writeln('        .load(script)');
    buffer.writeln('        .eval()');
    buffer.writeln('        .map_err(|e| e.to_string())?;');
    buffer.writeln();
    buffer.writeln('    match result {');
    buffer.writeln(
      '        Value::String(s) => Ok(s.to_string_lossy().to_owned()),',
    );
    buffer.writeln(
      '        _ => Err("Lua script must return a widget (string)".to_string()),',
    );
    buffer.writeln('    }');
    buffer.writeln('}');
  }

  void _writeInlineHelpers(StringBuffer buffer) {
    buffer.writeln(r'''
/// Inlined catalog helpers (no host `state` / `callbacks` modules required).
mod catalog_state {
    use serde_json::Value;
    use std::collections::HashMap;
    use std::sync::{Mutex, OnceLock};

    fn store() -> &'static Mutex<HashMap<String, Value>> {
        static STORE: OnceLock<Mutex<HashMap<String, Value>>> = OnceLock::new();
        STORE.get_or_init(|| Mutex::new(HashMap::new()))
    }

    pub fn get_state(key: &str) -> Result<String, String> {
        let guard = store().lock().map_err(|e| e.to_string())?;
        guard
            .get(key)
            .map(|v| v.to_string())
            .ok_or_else(|| format!("State key '{key}' not found"))
    }

    pub fn set_state(key: String, value: String) -> Result<(), String> {
        let json_value: Value =
            serde_json::from_str(&value).map_err(|e| format!("Invalid JSON: {e}"))?;
        let mut guard = store().lock().map_err(|e| e.to_string())?;
        guard.insert(key, json_value);
        Ok(())
    }

    pub fn get_all_state() -> Result<String, String> {
        let guard = store().lock().map_err(|e| e.to_string())?;
        serde_json::to_string(&*guard).map_err(|e| e.to_string())
    }
}

mod catalog_callbacks {
    use mlua::{Function, Lua, RegistryKey, Result};
    use std::collections::HashMap;
    use std::sync::{Mutex, OnceLock};

    fn store() -> &'static Mutex<(u64, HashMap<String, RegistryKey>)> {
        static STORE: OnceLock<Mutex<(u64, HashMap<String, RegistryKey>)>> = OnceLock::new();
        STORE.get_or_init(|| Mutex::new((0, HashMap::new())))
    }

    pub fn register_callback(lua: &Lua, func: Function) -> Result<String> {
        let key = lua.create_registry_value(func)?;
        let mut guard = store().lock().map_err(|e| mlua::Error::runtime(e.to_string()))?;
        guard.0 += 1;
        let id = format!("cb-{}", guard.0);
        guard.1.insert(id.clone(), key);
        Ok(id)
    }
}
''');
  }

  String _getRustPrimitiveType(PropertyInfo prop) {
    final cleanType = prop.nonNullableDartType;

    switch (cleanType) {
      case 'String':
        return 'String';
      case 'int':
        return 'i64';
      case 'double':
        return 'f64';
      case 'bool':
        return 'bool';
      case 'num':
        return 'f64';
      default:
        return 'String';
    }
  }
}

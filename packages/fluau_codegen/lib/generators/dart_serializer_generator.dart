/// Dart serializer generator for Lua plugin framework
///
/// Generates a standalone library:
/// - fromJson() per generative constructor
/// - LuaWidgetRegistry with type-to-constructor mapping
/// - Helper methods for deserialization
/// - Enum parsers for enum properties

import 'package:path/path.dart' as path;

import '../fluau_config.dart';
import '../models/widget_info.dart';

/// Main Dart serializer generator
class DartSerializerGenerator {
  /// Set of enum types that have already had parsers generated
  final Set<String> _generatedEnumParsers = {};

  /// Buffer for collecting enum parser functions
  final StringBuffer _enumParsersBuffer = StringBuffer();

  /// Generate all serialization code for the given classes.
  ///
  /// [outputFile] is the absolute path of `widget_serializers.g.dart`.
  /// [packageRoot] / [packageName] produce `package:` imports for widget sources.
  String generateAll(
    List<LuaClassInfo> classes, {
    required String outputFile,
    required String packageRoot,
    String? packageName,
  }) {
    final buffer = StringBuffer();

    _writeHeader(
      buffer,
      classes: classes,
      outputFile: outputFile,
      packageRoot: packageRoot,
      packageName: packageName,
    );
    buffer.writeln();

    for (final luaClass in classes) {
      _writeSerializer(buffer, luaClass, classes);
      buffer.writeln();
    }

    buffer.writeln(_enumParsersBuffer.toString());
    _writeRegistry(buffer, classes);

    return buffer.toString();
  }

  /// Reset the generator state (for testing)
  void clear() {
    _generatedEnumParsers.clear();
    _enumParsersBuffer.clear();
  }

  void _writeHeader(
    StringBuffer buffer, {
    required List<LuaClassInfo> classes,
    required String outputFile,
    required String packageRoot,
    String? packageName,
  }) {
    buffer.writeln('// Generated by fluau_codegen');
    buffer.writeln('// DO NOT EDIT - This file is automatically generated');
    buffer.writeln();
    buffer.writeln("import 'package:flutter/widgets.dart';");
    buffer.writeln("import 'package:fluau/fluau.dart';");

    final imports = <String>{};
    for (final luaClass in classes) {
      final imp = _importForSource(
        luaClass.sourceFile,
        packageRoot: packageRoot,
        packageName: packageName,
        outputFile: outputFile,
      );
      if (imp != null) imports.add(imp);
      for (final ctor in luaClass.constructors) {
        for (final prop in ctor.parameters) {
          final typeSrc = prop.typeSourceFile;
          if (typeSrc == null) continue;
          final typeImp = _importForSource(
            typeSrc,
            packageRoot: packageRoot,
            packageName: packageName,
            outputFile: outputFile,
          );
          if (typeImp != null) imports.add(typeImp);
        }
      }
    }

    final sorted = imports.toList()..sort();
    for (final imp in sorted) {
      buffer.writeln("import '$imp';");
    }
  }

  String? _importForSource(
    String absoluteSource, {
    required String packageRoot,
    required String? packageName,
    required String outputFile,
  }) {
    final normalized = path.normalize(absoluteSource);
    if (path.normalize(outputFile) == normalized) return null;

    if (packageName != null) {
      final pkg = packageImportForFile(
        absoluteFilePath: normalized,
        packageRoot: packageRoot,
        packageName: packageName,
      );
      if (pkg != null) return pkg;
    }

    // Fallback: relative import from the generated file.
    var rel = path.relative(normalized, from: path.dirname(outputFile));
    rel = rel.replaceAll(r'\', '/');
    if (!rel.startsWith('.')) rel = './$rel';
    return rel;
  }

  void _writeSerializer(
    StringBuffer buffer,
    LuaClassInfo luaClass,
    List<LuaClassInfo> allClasses,
  ) {
    final className = luaClass.dartClassName;

    buffer.writeln('/// Serializer for $className');
    buffer.writeln('/// Converts JSON maps to $className instances');
    buffer.writeln('extension _${className}Serializer on $className {');

    for (final ctor in luaClass.constructors) {
      final methodName = ctor.isUnnamed
          ? 'fromJson'
          : 'fromJson_${ctor.dartName}';
      final call = ctor.dartCall(className);

      buffer.writeln('  /// Deserialize via `${ctor.luaName}`');
      buffer.writeln(
        '  static $className $methodName(Map<String, dynamic> json) {',
      );
      buffer.writeln('    return $call(');

      for (final prop in ctor.parameters) {
        final value = _generatePropertyValue(prop, luaClass, allClasses);
        if (prop.isNamed) {
          buffer.writeln('      ${prop.dartParamName}: $value,');
        } else {
          buffer.writeln('      $value,');
        }
      }

      buffer.writeln('    );');
      buffer.writeln('  }');
      buffer.writeln();
    }

    buffer.writeln('}');
  }

  String _generatePropertyValue(
    PropertyInfo prop,
    LuaClassInfo luaClass,
    List<LuaClassInfo> allClasses,
  ) {
    final jsonKey = prop.name;

    if (prop.isCallback) {
      if (prop.omitWhenAbsent) {
        final fallback = prop.defaultValueCode ?? 'null';
        return 'json.containsKey(\'$jsonKey\') '
            '? Map<String, dynamic>.from(json[\'$jsonKey\'] as Map) '
            ': $fallback';
      }
      if (prop.isNullable) {
        return 'json[\'$jsonKey\'] != null ? Map<String, dynamic>.from(json[\'$jsonKey\'] as Map) : null';
      }
      return 'Map<String, dynamic>.from(json[\'$jsonKey\'] as Map)';
    }

    if (prop.isChildList) {
      return '_deserializeWidgetList(json[\'$jsonKey\'] as List?)';
    }

    if (prop.isStringList) {
      if (prop.omitWhenAbsent) {
        final fallback = prop.defaultValueCode ?? 'const <String>[]';
        return 'json.containsKey(\'$jsonKey\') '
            '? (json[\'$jsonKey\'] as List).map((e) => e.toString()).toList() '
            ': $fallback';
      }
      if (prop.isNullable) {
        return 'json[\'$jsonKey\'] != null '
            '? (json[\'$jsonKey\'] as List).map((e) => e.toString()).toList() '
            ': null';
      }
      return '(json[\'$jsonKey\'] as List).map((e) => e.toString()).toList()';
    }

    if (prop.isChildWidget) {
      if (prop.omitWhenAbsent) {
        final fallback = prop.defaultValueCode ?? 'null';
        return 'json.containsKey(\'$jsonKey\') '
            '? _deserializeWidget(json[\'$jsonKey\'] as Map<String, dynamic>) '
            ': $fallback';
      }
      if (prop.isNullable) {
        return 'json[\'$jsonKey\'] != null ? _deserializeWidget(json[\'$jsonKey\'] as Map<String, dynamic>) : null';
      }
      return '_deserializeWidget(json[\'$jsonKey\'] as Map<String, dynamic>)';
    }

    if (prop.isDataClass) {
      final nestedClassName = prop.nestedClassName ?? prop.nonNullableDartType;
      if (prop.omitWhenAbsent) {
        final fallback = prop.defaultValueCode ?? 'null';
        return 'json.containsKey(\'$jsonKey\') '
            '? _${nestedClassName}Serializer.fromJson(json[\'$jsonKey\'] as Map<String, dynamic>) '
            ': $fallback';
      }
      if (prop.isNullable) {
        return 'json[\'$jsonKey\'] != null ? _${nestedClassName}Serializer.fromJson(json[\'$jsonKey\'] as Map<String, dynamic>) : null';
      }
      return '_${nestedClassName}Serializer.fromJson(json[\'$jsonKey\'] as Map<String, dynamic>)';
    }

    if (prop.isEnum) {
      final enumType = prop.nonNullableDartType;
      _generateEnumParser(enumType, prop.enumValues ?? []);
      if (prop.omitWhenAbsent) {
        final fallback = prop.defaultValueCode ?? 'null';
        return 'json.containsKey(\'$jsonKey\') '
            '? _parse$enumType(json[\'$jsonKey\'] as String?)! '
            ': $fallback';
      }
      if (prop.isNullable) {
        return 'json[\'$jsonKey\'] != null ? _parse$enumType(json[\'$jsonKey\'] as String?) : null';
      }
      return '_parse$enumType(json[\'$jsonKey\'] as String?)!';
    }

    return _generatePrimitiveValue(prop);
  }

  void _generateEnumParser(String enumType, List<String> values) {
    if (_generatedEnumParsers.contains(enumType)) return;
    _generatedEnumParsers.add(enumType);

    _enumParsersBuffer.writeln('$enumType? _parse$enumType(String? value) {');
    _enumParsersBuffer.writeln('  if (value == null) return null;');
    _enumParsersBuffer.writeln('  switch (value) {');
    for (final val in values) {
      _enumParsersBuffer.writeln('    case \'$val\': return $enumType.$val;');
    }
    _enumParsersBuffer.writeln(
      '    default: throw FormatException(\'Unknown $enumType value: \$value\');',
    );
    _enumParsersBuffer.writeln('  }');
    _enumParsersBuffer.writeln('}');
    _enumParsersBuffer.writeln();
  }

  String _generatePrimitiveValue(PropertyInfo prop) {
    final jsonKey = prop.name;
    final type = TypeMapping.getForDartType(prop.dartType);
    final cleanType = prop.nonNullableDartType;

    // Non-nullable + Dart default: do not pass null; use default when absent.
    if (prop.omitWhenAbsent) {
      final parsed = type != null
          ? type.dartFromJson.replaceAll('value', 'json[\'$jsonKey\']')
          : 'json[\'$jsonKey\'] as $cleanType';
      final fallback = prop.defaultValueCode ?? 'null /* missing default */';
      return 'json.containsKey(\'$jsonKey\') ? $parsed : $fallback';
    }

    if (type != null) {
      if (prop.isNullable) {
        final expression =
            type.dartFromJson.replaceAll('value', 'json[\'$jsonKey\']');
        return 'json[\'$jsonKey\'] != null ? $expression : null';
      } else {
        return type.dartFromJson.replaceAll('value', 'json[\'$jsonKey\']');
      }
    }

    if (prop.isNullable) {
      return 'json[\'$jsonKey\'] as $cleanType?';
    } else {
      return 'json[\'$jsonKey\'] as $cleanType';
    }
  }

  void _writeRegistry(StringBuffer buffer, List<LuaClassInfo> classes) {
    buffer.writeln('/// Widget registry for Lua widgets');
    buffer.writeln(
      '/// Maps widget type names to their deserialization functions',
    );
    buffer.writeln('class LuaWidgetRegistry {');
    buffer.writeln(
      '  static final Map<String, LuaWidgetInterface Function(Map<String, dynamic>)> _builders = {',
    );

    for (final luaClass in classes.where((c) => c.isWidget)) {
      for (final ctor in luaClass.constructors) {
        final methodName = ctor.isUnnamed
            ? 'fromJson'
            : 'fromJson_${ctor.dartName}';
        buffer.writeln(
          '    \'${ctor.luaName}\': (json) => '
          '_${luaClass.dartClassName}Serializer.$methodName(json),',
        );
      }
    }

    buffer.writeln('  };');
    buffer.writeln();
    buffer.writeln('  /// Deserialize a widget from JSON (without building it)');
    buffer.writeln(
      '  /// The [type] parameter should be the Lua widget type name (e.g., \'Text\', \'Button\').',
    );
    buffer.writeln(
      '  static LuaWidgetInterface fromJson(String type, Map<String, dynamic> json) {',
    );
    buffer.writeln('    final builder = _builders[type];');
    buffer.writeln('    if (builder != null) {');
    buffer.writeln('      return builder(json);');
    buffer.writeln('    }');
    buffer.writeln('    return const LuaEmptyWidget();');
    buffer.writeln('  }');
    buffer.writeln();
    buffer.writeln(
      '  /// Build a widget from a JSON map (with type field) and context',
    );
    buffer.writeln(
      '  /// This is the main entry point for building widgets from Lua JSON.',
    );
    buffer.writeln(
      '  static Widget buildFromMap(BuildContext context, Map<String, dynamic> widgetMap) {',
    );
    buffer.writeln('    final widgetType = widgetMap[\'type\'] as String?;');
    buffer.writeln('    if (widgetType == null) {');
    buffer.writeln('      return const LuaEmptyWidget().build(context);');
    buffer.writeln('    }');
    buffer.writeln();
    buffer.writeln('    // Remove type from properties');
    buffer.writeln(
      '    final properties = Map<String, dynamic>.from(widgetMap);',
    );
    buffer.writeln('    properties.remove(\'type\');');
    buffer.writeln();
    buffer.writeln('    // Deserialize and build');
    buffer.writeln('    final widget = fromJson(widgetType, properties);');
    buffer.writeln('    return widget.build(context);');
    buffer.writeln('  }');
    buffer.writeln('}');
    buffer.writeln();

    _writeHelperFunctions(buffer);
  }

  void _writeHelperFunctions(StringBuffer buffer) {
    buffer.writeln('/// Deserialize a list of child widgets from JSON');
    buffer.writeln(
      '/// Each child widget JSON should have a "type" field indicating its widget type.',
    );
    buffer.writeln(
      'List<LuaWidgetInterface> _deserializeWidgetList(List<dynamic>? json) {',
    );
    buffer.writeln('  if (json == null) return [];');
    buffer.writeln(
      '  return json.map((item) => _deserializeWidget(item as Map<String, dynamic>)).toList();',
    );
    buffer.writeln('}');
    buffer.writeln();

    buffer.writeln('/// Deserialize a single widget from JSON');
    buffer.writeln(
      '/// This creates the widget instance but does NOT build it.',
    );
    buffer.writeln(
      '/// The build() method will be called later with proper BuildContext.',
    );
    buffer.writeln(
      '/// The JSON should have a "type" field indicating the widget type.',
    );
    buffer.writeln(
      'LuaWidgetInterface _deserializeWidget(Map<String, dynamic> json) {',
    );
    buffer.writeln('  final widgetType = json[\'type\'] as String?;');
    buffer.writeln('  if (widgetType == null) {');
    buffer.writeln('    return const LuaEmptyWidget();');
    buffer.writeln('  }');
    buffer.writeln();
    buffer.writeln('  // Remove type from the JSON before deserializing');
    buffer.writeln('  final properties = Map<String, dynamic>.from(json);');
    buffer.writeln('  properties.remove(\'type\');');
    buffer.writeln();
    buffer.writeln('  // Use the registry to deserialize');
    buffer.writeln(
      '  return LuaWidgetRegistry.fromJson(widgetType, properties);',
    );
    buffer.writeln('}');
    buffer.writeln();
  }
}

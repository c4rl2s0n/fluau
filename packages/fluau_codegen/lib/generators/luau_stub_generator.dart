/// Luau definition stub generator for the Lua plugin framework.
///
/// Emits `.d.luau` files consumable by luau-lsp from annotated Dart widgets.
library;

import '../models/widget_info.dart';

/// Generates Luau type stubs for the `ui` widget catalog.
class LuauStubGenerator {
  /// Generate a complete `ui.d.luau` definition file.
  String generate(List<LuaClassInfo> classes) {
    final buffer = StringBuffer();
    _writeHeader(buffer);

    buffer.writeln('export type EventPayload = { [string]: any }');
    buffer.writeln('export type Widget = string');
    buffer.writeln();

    _writeEnumAliases(buffer, classes);
    _writeDataClassTypes(buffer, classes.where((c) => !c.isWidget).toList());
    _writeWidgetPropTypes(buffer, classes.where((c) => c.isWidget).toList());
    _writeUiDeclare(buffer, classes.where((c) => c.isWidget).toList());

    return buffer.toString();
  }

  void _writeHeader(StringBuffer buffer) {
    buffer.writeln('-- Generated by fluau_codegen');
    buffer.writeln('-- DO NOT EDIT - This file is automatically generated');
    buffer.writeln();
  }

  void _writeEnumAliases(StringBuffer buffer, List<LuaClassInfo> classes) {
    final enums = <String, List<String>>{};
    for (final luaClass in classes) {
      for (final ctor in luaClass.constructors) {
        for (final prop in ctor.parameters) {
          if (!prop.isEnum || prop.enumValues == null) continue;
          final typeName = prop.nonNullableDartType;
          enums.putIfAbsent(typeName, () => List<String>.from(prop.enumValues!));
        }
      }
    }

    if (enums.isEmpty) return;

    final names = enums.keys.toList()..sort();
    for (final name in names) {
      final union = enums[name]!.map((v) => '"$v"').join(' | ');
      buffer.writeln('export type $name = $union');
    }
    buffer.writeln();
  }

  void _writeDataClassTypes(
    StringBuffer buffer,
    List<LuaClassInfo> dataClasses,
  ) {
    if (dataClasses.isEmpty) return;

    for (final dataClass in dataClasses) {
      for (final ctor in dataClass.constructors) {
        final typeName = ctor.isUnnamed
            ? dataClass.luaName
            : '${dataClass.luaName}_${ctor.dartName}';
        buffer.writeln('export type $typeName = {');
        for (final prop in ctor.parameters) {
          buffer.writeln(
            '  ${prop.name}: ${_luauType(prop)}${_optionalSuffix(prop)},',
          );
        }
        buffer.writeln('}');
        buffer.writeln();
      }
    }
  }

  void _writeWidgetPropTypes(StringBuffer buffer, List<LuaClassInfo> widgets) {
    for (final widget in widgets) {
      for (final ctor in widget.constructors) {
        buffer.writeln('export type ${ctor.luaName}Props = {');
        for (final prop in ctor.parameters) {
          buffer.writeln(
            '  ${prop.name}: ${_luauType(prop)}${_optionalSuffix(prop)},',
          );
        }
        buffer.writeln('}');
        buffer.writeln();
      }
    }
  }

  void _writeUiDeclare(StringBuffer buffer, List<LuaClassInfo> widgets) {
    buffer.writeln('declare ui: {');
    for (final widget in widgets) {
      for (final ctor in widget.constructors) {
        buffer.writeln(
          '  ${ctor.luaName}: (props: ${ctor.luaName}Props) -> Widget,',
        );
      }
    }
    buffer.writeln('  getState: (key: string) -> string?,');
    buffer.writeln('  setState: (key: string, value: string) -> (),');
    buffer.writeln('  getAllState: () -> string,');
    buffer.writeln('  registerCallback: (callback: (...any) -> ()) -> (),');
    buffer.writeln('}');
    buffer.writeln();
  }

  String _optionalSuffix(PropertyInfo prop) {
    // Required = non-nullable with no Dart default.
    if (prop.required) return '';
    return '?';
  }

  String _luauType(PropertyInfo prop) {
    if (prop.isCallback) return 'EventPayload';
    if (prop.isChildWidget) return 'Widget';
    if (prop.isChildList) return '{Widget}';
    if (prop.isStringList) return '{string}';
    if (prop.isEnum) return prop.nonNullableDartType;
    if (prop.isDataClass) {
      return prop.nestedClassName ?? prop.nonNullableDartType;
    }

    final info = TypeMapping.getForDartType(prop.dartType);
    if (info != null) {
      if (info.lua == 'integer' || info.lua == 'number') return 'number';
      if (info.lua == 'boolean') return 'boolean';
      if (info.lua == 'string') return 'string';
      return 'any';
    }

    return 'any';
  }
}

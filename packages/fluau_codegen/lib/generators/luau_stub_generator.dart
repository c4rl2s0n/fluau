/// Luau definition stub generator for the Lua plugin framework.
///
/// Emits `.d.luau` files consumable by luau-lsp from annotated Dart widgets.
library;

import '../models/widget_info.dart';

/// Generates Luau type stubs for the `ui` widget catalog.
class LuauStubGenerator {
  /// Generate a complete `ui.d.luau` definition file.
  String generate(
    List<LuaClassInfo> classes, {
    List<LuaEnumInfo> enums = const [],
  }) {
    final buffer = StringBuffer();
    _writeHeader(buffer);

    buffer.writeln('export type EventPayload = { [string]: any }');
    buffer.writeln(
      '-- Callback props: event payload table, or a Lua function (runtime registers',
    );
    buffer.writeln(
      '-- a reserved `{ type = "action", id }` payload; do not emit type "action" by hand).',
    );
    buffer.writeln(
      'export type UiCallback = EventPayload | ((event: EventPayload) -> any)',
    );
    buffer.writeln('export type Widget = string');
    buffer.writeln();

    final catalogEnums = _mergeEnums(classes, enums);
    _writeEnumAliases(buffer, catalogEnums);
    _writeEnumsDeclare(buffer, catalogEnums);
    _writeDataClassTypes(buffer, classes.where((c) => !c.isWidget).toList());
    _writeWidgetPropTypes(buffer, classes.where((c) => c.isWidget).toList());
    _writeUiDeclare(buffer, classes.where((c) => c.isWidget).toList());

    return buffer.toString();
  }

  void _writeHeader(StringBuffer buffer) {
    buffer.writeln('-- Generated by fluau_codegen');
    buffer.writeln('-- DO NOT EDIT - This file is automatically generated');
    buffer.writeln();
  }

  List<LuaEnumInfo> _mergeEnums(
    List<LuaClassInfo> classes,
    List<LuaEnumInfo> enums,
  ) {
    final byLua = <String, LuaEnumInfo>{};
    for (final e in enums) {
      byLua[e.luaName] = e;
    }
    for (final luaClass in classes) {
      for (final ctor in luaClass.constructors) {
        for (final prop in ctor.parameters) {
          if (!prop.isEnum || prop.enumValues == null) continue;
          final luaName = prop.enumLuaName ?? prop.nonNullableDartType;
          byLua.putIfAbsent(
            luaName,
            () => LuaEnumInfo(
              dartName: prop.nonNullableDartType,
              luaName: luaName,
              values: List<String>.from(prop.enumValues!),
              sourceFile: prop.typeSourceFile ?? '',
            ),
          );
        }
      }
    }
    return byLua.values.toList()..sort((a, b) => a.luaName.compareTo(b.luaName));
  }

  void _writeEnumAliases(StringBuffer buffer, List<LuaEnumInfo> enums) {
    if (enums.isEmpty) return;
    for (final e in enums) {
      final union = e.values.map((v) => '"$v"').join(' | ');
      buffer.writeln('export type ${e.luaName} = $union');
    }
    buffer.writeln();
  }

  void _writeEnumsDeclare(StringBuffer buffer, List<LuaEnumInfo> enums) {
    if (enums.isEmpty) return;
    buffer.writeln('declare enums: {');
    for (final e in enums) {
      final members = e.values.map((v) => '$v: "$v"').join(', ');
      buffer.writeln('  ${e.luaName}: { $members },');
    }
    buffer.writeln('}');
    buffer.writeln();
  }

  void _writeDataClassTypes(
    StringBuffer buffer,
    List<LuaClassInfo> dataClasses,
  ) {
    if (dataClasses.isEmpty) return;

    for (final dataClass in dataClasses) {
      for (final ctor in dataClass.constructors) {
        final typeName = ctor.isUnnamed
            ? dataClass.luaName
            : '${dataClass.luaName}_${ctor.dartName}';
        buffer.writeln('export type $typeName = {');
        for (final prop in ctor.parameters) {
          buffer.writeln(
            '  ${prop.name}: ${_luauType(prop)}${_optionalSuffix(prop)},',
          );
        }
        buffer.writeln('}');
        buffer.writeln();
      }
    }
  }

  void _writeWidgetPropTypes(StringBuffer buffer, List<LuaClassInfo> widgets) {
    for (final widget in widgets) {
      for (final ctor in widget.constructors) {
        final propsName = propsTypeName(ctor.luaName);
        buffer.writeln('export type $propsName = {');
        for (final prop in ctor.parameters) {
          buffer.writeln(
            '  ${prop.name}: ${_luauType(prop)}${_optionalSuffix(prop)},',
          );
        }
        buffer.writeln('}');
        buffer.writeln();
      }
    }
  }

  void _writeUiDeclare(StringBuffer buffer, List<LuaClassInfo> widgets) {
    final root = _NsNode();
    for (final widget in widgets) {
      for (final ctor in widget.constructors) {
        final parts = ctor.luaName.split('.');
        var node = root;
        for (var i = 0; i < parts.length - 1; i++) {
          node = node.child(parts[i]);
        }
        node.leaves[parts.last] = ctor.luaName;
      }
    }

    buffer.writeln('declare ui: {');
    _writeNsNode(buffer, root, indent: 1);
    buffer.writeln('  getState: (key: string) -> string?,');
    buffer.writeln('  setState: (key: string, value: string) -> (),');
    buffer.writeln('  getAllState: () -> string,');
    buffer.writeln(
      '  -- Registers fn for this render; returns payload (optional extra fields).',
    );
    buffer.writeln(
      '  action: (fn: (event: EventPayload) -> any, extra: EventPayload?) -> EventPayload,',
    );
    buffer.writeln('}');
    buffer.writeln();
  }

  void _writeNsNode(StringBuffer buffer, _NsNode node, {required int indent}) {
    final pad = '  ' * indent;
    final keys = [...node.children.keys, ...node.leaves.keys]..sort();
    for (final key in keys) {
      if (node.children.containsKey(key)) {
        buffer.writeln('$pad$key: {');
        _writeNsNode(buffer, node.children[key]!, indent: indent + 1);
        buffer.writeln('$pad},');
      } else {
        final fullName = node.leaves[key]!;
        final props = propsTypeName(fullName);
        buffer.writeln('$pad$key: (props: $props) -> Widget,');
      }
    }
  }

  String _optionalSuffix(PropertyInfo prop) {
    // Required = non-nullable with no Dart default.
    if (prop.required) return '';
    return '?';
  }

  String _luauType(PropertyInfo prop) {
    if (prop.isCallback) return 'UiCallback';
    if (prop.isChildWidget) return 'Widget';
    if (prop.isChildList) return '{Widget}';
    if (prop.isStringList) return '{string}';
    if (prop.isEnum) return prop.enumLuaName ?? prop.nonNullableDartType;
    if (prop.isDataClass) {
      return prop.nestedClassName ?? prop.nonNullableDartType;
    }

    final info = TypeMapping.getForDartType(prop.dartType);
    if (info != null) {
      if (info.lua == 'integer' || info.lua == 'number') return 'number';
      if (info.lua == 'boolean') return 'boolean';
      if (info.lua == 'string') return 'string';
      return 'any';
    }

    return 'any';
  }
}

/// Props type for a Lua ctor name.
///
/// Flat: `Text` → `TextProps`, `Text_styled` → `Text_styledProps`.
/// Dotted: `layout.column` → `LayoutColumnProps`.
String propsTypeName(String luaName) {
  if (!luaName.contains('.')) {
    return '${luaName}Props';
  }
  final buf = StringBuffer();
  for (final segment in luaName.split('.')) {
    for (final part in segment.split('_')) {
      if (part.isEmpty) continue;
      buf.write(part[0].toUpperCase());
      if (part.length > 1) buf.write(part.substring(1));
    }
  }
  buf.write('Props');
  return buf.toString();
}

class _NsNode {
  final Map<String, _NsNode> children = {};
  final Map<String, String> leaves = {};

  _NsNode child(String name) => children.putIfAbsent(name, _NsNode.new);
}

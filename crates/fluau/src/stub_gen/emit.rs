//! Emit Luau definition stubs from a HostApiModel.

use super::model::{HostApiModel, HostMethod, LuauType};

pub fn emit_luau(model: &HostApiModel) -> String {
    let mut out = String::new();
    out.push_str("-- Generated by fluau stub-gen (rust build.rs). DO NOT EDIT.\n\n");

    for ty in &model.types {
        out.push_str(&format!("export type {} = {{\n", ty.name));
        for f in &ty.fields {
            out.push_str(&format!("\t{}: {},\n", f.name, f.ty.to_luau()));
        }
        out.push_str("}\n\n");
    }

    for ud in &model.userdata {
        out.push_str(&format!("declare class {}\n", ud.name));
        for m in &ud.methods {
            out.push_str(&format!("\t{}\n", method_line(m, true)));
        }
        out.push_str("end\n\n");
    }

    out.push_str("declare host: {\n");
    for module in &model.modules {
        out.push_str(&format!("\t{}: {{\n", module.path));
        for m in &module.methods {
            out.push_str(&format!("\t\t{}: {},\n", m.lua_name, method_fn_type(m)));
        }
        out.push_str("\t},\n");
    }
    out.push_str("}\n");

    out
}

fn method_line(m: &HostMethod, as_class_method: bool) -> String {
    let params = m
        .params
        .iter()
        .map(|(n, t)| format!("{n}: {}", t.to_luau()))
        .collect::<Vec<_>>()
        .join(", ");
    let ret = match &m.ret {
        LuauType::Nil => "()".to_string(),
        other => other.to_luau(),
    };
    if as_class_method {
        if params.is_empty() {
            format!("function {}(self): {}", m.lua_name, ret)
        } else {
            format!("function {}(self, {}): {}", m.lua_name, params, ret)
        }
    } else {
        method_fn_type(m)
    }
}

fn method_fn_type(m: &HostMethod) -> String {
    let params = m
        .params
        .iter()
        .map(|(n, t)| format!("{n}: {}", t.to_luau()))
        .collect::<Vec<_>>()
        .join(", ");
    let ret = match &m.ret {
        LuauType::Nil => "()".to_string(),
        other => other.to_luau(),
    };
    format!("({params}) -> {ret}")
}
